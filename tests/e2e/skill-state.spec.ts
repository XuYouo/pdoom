import { expect, test } from '@playwright/test';

test('real E effect and cooldown remain distinct, keep keyboard focus, and freeze while paused', async ({ page }, info) => {
  await page.goto('/');
  await page.getByRole('button', { name: '开始新训练', exact: true }).click();
  const skill = (key: string) => page.locator('.game-actions .skill-button').filter({ has: page.locator('kbd', { hasText: new RegExp(`^${key}$`) }) });
  const q = skill('Q'), e = skill('E');
  await expect(q).toHaveAttribute('data-state', 'recording');
  await expect(q).toBeDisabled();
  await expect(q).toContainText('记录');
  await e.focus(); await page.keyboard.press('Enter');
  await expect(e).toHaveAttribute('aria-pressed', 'true');
  await expect(e).toHaveAttribute('aria-disabled', 'true');
  expect(await e.evaluate(element => (element as HTMLButtonElement).disabled)).toBe(false);
  await expect(e).toBeFocused();
  await page.keyboard.press('Enter'); await page.keyboard.press('Space');
  await expect(e).toBeFocused();
  await expect(e).toContainText('透视中');
  await page.screenshot({ path: info.outputPath('insight-active-keyboard.png') });
  await page.keyboard.press('Escape');
  const paused = page.getByRole('dialog', { name: '暂停前向传播。', exact: true });
  await expect(paused).toBeVisible();
  const frozen = await e.locator('.skill-countdown').textContent();
  await page.waitForTimeout(450);
  expect(await e.locator('.skill-countdown').textContent()).toBe(frozen);
  await page.keyboard.press('Escape');
  await expect(e).toHaveAttribute('data-state', 'cooldown', { timeout: 5000 });
  await expect(e).toHaveAttribute('aria-pressed', 'false');
  await expect(e).toHaveAttribute('aria-disabled', 'true');
  await expect(e).toContainText('冷却');
  await e.focus(); await page.keyboard.press('Enter');
  await expect(e).toBeFocused(); await expect(e).toHaveAttribute('aria-pressed', 'false');
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button', { name: '上下文详情', exact: true })).toBeFocused();
  await page.keyboard.press('Shift+Tab'); await expect(e).toBeFocused();
  await page.screenshot({ path: info.outputPath('insight-cooldown-keyboard.png') });
  await expect(e).toHaveAttribute('aria-disabled', 'false', { timeout: 5000 });
  await expect(e).toHaveAttribute('data-state', 'ready');
  await page.keyboard.press('Enter');
  await expect(e).toHaveAttribute('aria-pressed', 'true');
  await expect(e).toBeFocused();
});
